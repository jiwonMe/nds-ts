import type { CartridgeInfo } from './cartridges.js';
import { createWatchdog, loadCompiler, type Diagnostic } from './compiler.js';
import type { Program } from './console.js';
import { highlight } from './highlight.js';

type View = 'source' | 'script' | 'header';

export interface Loaded {
  info: CartridgeInfo;
  source: string;
  script: string;
  boot: NonNullable<Program['boot']>;
}

interface EditorHooks {
  /** Boots a program on the console; `edited` marks code that differs from the example. */
  run(program: Program, edited: boolean): void;
  /** Reports the ES5 size of whatever the console now runs. */
  compiled(bytes: number): void;
}

const $ = <T extends HTMLElement>(selector: string) => document.querySelector<T>(selector)!;
const bytesOf = (text: string) => new TextEncoder().encode(text).length;
const number = (value: number) => value.toLocaleString('en-US');

/** script_gen.h exactly as tools/build-script.ts writes it. */
export function header(script: string): string {
  const bytes = new TextEncoder().encode(script);
  const rows: string[] = [];
  for (let start = 0; start < bytes.length; start += 16) {
    rows.push('  ' + Array.from(bytes.subarray(start, start + 16), (byte) => `0x${byte.toString(16).padStart(2, '0')}`).join(', ') + ',');
  }
  return [
    '// Generated by tools/build-script.ts. Do not edit.',
    '#pragma once',
    'static const unsigned char GAME_SCRIPT[] = {',
    ...rows,
    '  0x00',
    '};',
    `static const unsigned int GAME_SCRIPT_LENGTH = ${bytes.length};`,
    '',
  ].join('\n');
}

const canEvaluate = (() => {
  try {
    return new Function('return true')() as boolean;
  } catch {
    return false;
  }
})();

export class Editor {
  private loaded: Loaded | null = null;
  private source = '';
  private script = '';
  private view: View = 'source';
  private pending = 0;
  private readonly input = $<HTMLTextAreaElement>('#code-input');
  private readonly painted = $<HTMLPreElement>('#code-highlight');
  private readonly gutter = $<HTMLDivElement>('#code-gutter');
  private readonly build = $<HTMLDivElement>('#build');
  private readonly state = $<HTMLParagraphElement>('#build-state');
  private readonly runButton = $<HTMLButtonElement>('#run-code');
  private readonly diagnostics = $<HTMLOListElement>('#diagnostics');
  private readonly tweaks = $<HTMLDivElement>('#tweaks');
  private readonly tabs = [...document.querySelectorAll<HTMLButtonElement>('.ide-tab')];

  constructor(private readonly hooks: EditorHooks) {
    this.input.addEventListener('input', () => {
      if (this.view !== 'source') return;
      this.source = this.input.value;
      this.schedulePaint();
      this.setState('edited', 'Edited. Run it to compile in your browser.');
      this.syncTweaks();
    });
    this.input.addEventListener('scroll', () => this.syncScroll());
    this.input.addEventListener('keydown', (event) => {
      if (event.key === 'Enter' && (event.ctrlKey || event.metaKey)) {
        event.preventDefault();
        void this.run();
      }
    });
    this.runButton.addEventListener('click', () => void this.run());
    $('#revert-code').addEventListener('click', () => this.revert());
    for (const tab of this.tabs) {
      tab.addEventListener('click', () => this.show(tab.dataset.view as View));
      tab.addEventListener('keydown', (event) => {
        if (event.key !== 'ArrowRight' && event.key !== 'ArrowLeft') return;
        const next = this.tabs[(this.tabs.indexOf(tab) + (event.key === 'ArrowRight' ? 1 : this.tabs.length - 1)) % this.tabs.length];
        next.focus();
        this.show(next.dataset.view as View);
      });
    }
  }

  load(loaded: Loaded): void {
    this.loaded = loaded;
    this.source = loaded.source;
    this.script = loaded.script;
    $('#ide-path').textContent = `examples/${loaded.info.id}/main.ts`;
    this.diagnostics.replaceChildren();
    this.renderTweaks();
    this.show('source', true);
    this.setState('ready', 'Compiled by the ROM toolchain');
    this.figures();
  }

  /** Warms up the compiler so the first Run is quick. */
  prefetch(): void {
    void loadCompiler().catch(() => {});
  }

  private show(view: View, force = false): void {
    if (view === this.view && !force) return;
    this.view = view;
    for (const tab of this.tabs) {
      const selected = tab.dataset.view === view;
      tab.setAttribute('aria-selected', String(selected));
      tab.tabIndex = selected ? 0 : -1;
    }
    $('#ide-view').setAttribute('aria-labelledby', `tab-${view}`);
    this.input.readOnly = view !== 'source';
    this.input.setAttribute('aria-label', view === 'source' ? 'Cartridge source code' : view === 'script' ? 'Compiled ES5 script, read only' : 'Generated C header, read only');
    this.input.value = this.text();
    this.input.scrollTop = 0;
    this.input.scrollLeft = 0;
    this.paint();
    this.syncScroll();
  }

  private text(): string {
    return this.view === 'source' ? this.source : this.view === 'script' ? this.script : header(this.script);
  }

  private schedulePaint(): void {
    cancelAnimationFrame(this.pending);
    this.pending = requestAnimationFrame(() => this.paint());
  }

  private paint(): void {
    const text = this.input.value;
    this.painted.innerHTML = highlight(text, this.view === 'header' ? 'c' : 'ts');
    const lines = text.split('\n').length;
    let numbers = '';
    for (let line = 1; line <= lines; line++) numbers += `${line}\n`;
    this.gutter.textContent = numbers;
    this.syncScroll();
  }

  private syncScroll(): void {
    this.painted.style.transform = `translate(${-this.input.scrollLeft}px, ${-this.input.scrollTop}px)`;
    this.gutter.scrollTop = this.input.scrollTop;
  }

  private figures(): void {
    $('#figure-lines').textContent = `${number(this.source.split('\n').length)} lines`;
    $('#figure-bytes').textContent = `${number(bytesOf(this.script))} bytes`;
  }

  private setState(state: 'ready' | 'edited' | 'busy' | 'error', message: string): void {
    this.build.dataset.state = state;
    this.state.textContent = message;
  }

  async run(): Promise<void> {
    const loaded = this.loaded;
    if (!loaded) return;
    if (this.view !== 'source') this.show('source');
    this.runButton.disabled = true;
    this.setState('busy', 'Loading the TypeScript compiler');
    try {
      const compiler = await loadCompiler();
      this.setState('busy', 'Compiling');
      const result = compiler.compile(this.source);
      if (!result.ok) {
        this.showDiagnostics(result.diagnostics);
        const count = result.diagnostics.length;
        this.setState('error', `${count} ${count === 1 ? 'error' : 'errors'}. The console keeps the last good build.`);
        return;
      }
      this.diagnostics.replaceChildren();
      this.script = result.script;
      this.figures();
      const original = this.source === loaded.source;
      const identical = original && result.script === loaded.script;
      if (!canEvaluate) {
        this.setState('ready', 'Compiled. This page cannot run new code, so run the site locally to try it.');
        return;
      }
      const watchdog = createWatchdog();
      this.hooks.run({ script: result.guarded, watchdog }, !original);
      this.hooks.compiled(bytesOf(result.script));
      this.setState('ready', identical
        ? `TypeScript ${compiler.version} in your browser produced the same ${number(bytesOf(result.script))} bytes as the toolchain`
        : `Compiled in your browser with TypeScript ${compiler.version}`);
    } catch (error) {
      this.setState('error', `The compiler could not load: ${error instanceof Error ? error.message : String(error)}`);
    } finally {
      this.runButton.disabled = false;
    }
  }

  /** The console stopped with a script error; mirror it next to the code. */
  runtimeError(message: string): void {
    this.setState('error', 'The console stopped. Fix the code and run it again.');
    const item = document.createElement('li');
    item.textContent = message;
    this.diagnostics.replaceChildren(item);
  }

  private revert(): void {
    const loaded = this.loaded;
    if (!loaded) return;
    this.load(loaded);
    this.hooks.run({ script: loaded.script, boot: loaded.boot }, false);
    this.hooks.compiled(bytesOf(loaded.script));
  }

  private showDiagnostics(diagnostics: Diagnostic[]): void {
    this.diagnostics.replaceChildren(...diagnostics.slice(0, 8).map((diagnostic) => {
      const item = document.createElement('li');
      if (diagnostic.line > 0) {
        const jump = document.createElement('button');
        jump.type = 'button';
        jump.textContent = `Line ${diagnostic.line}:${diagnostic.column}`;
        jump.addEventListener('click', () => this.reveal(diagnostic.line, diagnostic.column));
        item.append(jump, ' ');
      }
      item.append(diagnostic.message);
      return item;
    }));
  }

  private reveal(line: number, column: number): void {
    const lines = this.source.split('\n');
    let offset = 0;
    for (let index = 0; index < line - 1 && index < lines.length; index++) offset += lines[index].length + 1;
    offset += column - 1;
    this.input.focus();
    this.input.setSelectionRange(offset, offset);
    const lineHeight = parseFloat(getComputedStyle(this.input).lineHeight) || 21;
    this.input.scrollTop = Math.max(0, (line - 4) * lineHeight);
  }

  private renderTweaks(): void {
    const tweaks = this.loaded?.info.tweaks ?? [];
    this.tweaks.replaceChildren(...tweaks.map((tweak) => {
      const chip = document.createElement('button');
      chip.type = 'button';
      chip.className = 'chip';
      chip.setAttribute('aria-pressed', 'false');
      chip.textContent = tweak.label;
      chip.addEventListener('click', () => {
        if (this.view !== 'source') this.show('source');
        if (this.source.includes(tweak.replace)) this.source = this.source.replace(tweak.replace, tweak.find);
        else if (this.source.includes(tweak.find)) this.source = this.source.replace(tweak.find, tweak.replace);
        else return;
        this.input.value = this.source;
        this.paint();
        this.syncTweaks();
        void this.run();
      });
      return chip;
    }));
    this.syncTweaks();
  }

  private syncTweaks(): void {
    const tweaks = this.loaded?.info.tweaks ?? [];
    [...this.tweaks.children].forEach((chip, index) => {
      const tweak = tweaks[index];
      chip.setAttribute('aria-pressed', String(this.source.includes(tweak.replace)));
      (chip as HTMLButtonElement).disabled = !this.source.includes(tweak.replace) && !this.source.includes(tweak.find);
    });
  }
}

